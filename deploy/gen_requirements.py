"""Generate requirements-space.txt from the working WSL venv freeze.

Run inside WSL:  bash setup/run.sh deploy/gen_requirements.py

Transforms the freeze for the HF Space (Gradio SDK, no apt, CPU-only):
  - LIBERO / octo editable/local installs -> pinned codeload tarballs
    (both setup.py files have install_requires=[], so no dep conflicts)
  - dlimp -> pinned codeload tarball
  - jaxlib cuda build -> plain jaxlib==0.4.20 (CPU)
  - drops nvidia-* CUDA wheels
  - torch pinned to the +cpu wheel (extra-index-url line at top)
  - adds spaces (ZeroGPU SDK)
Everything else stays exactly as frozen in the validated venv.
"""

import re
import subprocess
import sys

LIBERO_TARBALL = "libero @ https://codeload.github.com/Lifelong-Robot-Learning/LIBERO/tar.gz/8f1084e3132a39270c3a13ebe37270a43ece2a01"
OCTO_TARBALL = "octo @ https://codeload.github.com/octo-models/octo/tar.gz/241fb3514b7c40957a86d869fecb7c7fc353f540"
DLIMP_TARBALL = "dlimp @ https://codeload.github.com/kvablack/dlimp/tar.gz/5edaa4691567873d495633f2708982b42edf1972"

DROP_PREFIXES = ("nvidia-",)          # CUDA wheels; Space runs CPU
DROP_EXACT = {"libero", "octo", "dlimp", "dlimp-src", "tensorflow-cpu"}  # tarballs / dupes


def pkg_name(line):
    m = re.match(r"\s*([A-Za-z0-9_.\-]+)\s*@", line)  # direct URL install
    if m:
        return m.group(1).lower().replace("_", "-")
    if "file://" in line:  # editable local install: name from path basename
        return line.rstrip("/").rsplit("/", 1)[-1].lower().replace("_", "-")
    m = re.match(r"\s*(?:-e\s+)?([A-Za-z0-9_.\-]+)", line)
    return m.group(1).lower().replace("_", "-") if m else ""


def main():
    out = subprocess.run(
        [sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True
    )
    freeze = out.stdout if out.returncode == 0 else ""
    if not freeze.strip():  # uv-managed venv has no pip; use uv
        out = subprocess.run(
            ["/root/.local/bin/uv", "pip", "freeze", "--python", sys.executable],
            capture_output=True, text=True,
        )
        freeze = out.stdout
    lines = []
    seen = set()
    for raw in freeze.splitlines():
        line = raw.strip()
        if not line:
            continue
        name = pkg_name(line)
        if not name or name in seen:
            continue
        seen.add(name)
        if name in DROP_EXACT or name.startswith(DROP_PREFIXES):
            continue
        if name == "jaxlib":
            line = "jaxlib==0.4.20"  # CPU build
        lines.append(line)

    header = [
        "# Auto-generated by deploy/gen_requirements.py from the validated WSL venv.",
        "# Do not hand-edit pins casually — see README 'Environment' for why each pin exists.",
        "--extra-index-url https://download.pytorch.org/whl/cpu",
        LIBERO_TARBALL,
        OCTO_TARBALL,
        DLIMP_TARBALL,
        "spaces",
    ]
    text = "\n".join(header + sorted(lines)) + "\n"
    with open("requirements-space.txt", "w") as f:
        f.write(text)
    print(text)
    bad = [l for l in text.splitlines() if "/root/" in l or "/mnt/" in l or "file:" in l]
    if bad:
        print("ERROR: local paths leaked:", bad)
        sys.exit(1)
    print(f"OK: {len(lines)} frozen deps + tarballs -> requirements-space.txt")


if __name__ == "__main__":
    main()
